import type { MockReview } from './types.js';

/**
 * Review đã duyệt của từng tour, khoá theo slug.
 *
 * KHÁC `tour-media.ts` ở một điểm quan trọng: media được GHÉP vào `MockTourDetail`
 * vì API thật cũng trả nó trong detail payload; review thì **không được ghép**, vì
 * API thật trả chúng qua một lời gọi RIÊNG có phân trang (`reviews.listByTour`,
 * `@Public()`, nhận `{tourSlug, page, pageSize}`). Giữ đúng ranh giới đó ngay từ
 * mock, nếu không lúc wire mới phát hiện UI đã được thiết kế quanh dữ liệu không
 * nằm ở chỗ mình tưởng.
 *
 * `ratingAvg`/`ratingCount` của tour được DẪN XUẤT từ đây (xem cuối `tours.ts`),
 * không viết tay: nhờ vậy con số ở hero là con số tính được từ chính danh sách
 * đang hiển thị, và "See all 12 reviews" mở ra đúng 12.
 *
 * Thứ tự trong từng mảng KHÔNG quan trọng — server sắp
 * `authorDeleted asc → createdAt desc`, và `tourReviews()` sắp lại y hệt.
 */

function rev(
  n: number,
  rating: number,
  author: string | null,
  createdAt: string,
  title: string | null,
  body: string,
): MockReview {
  return {
    id: `rv-${n}`,
    rating,
    title,
    body,
    authorName: author,
    authorDeleted: author === null,
    createdAt,
  };
}

